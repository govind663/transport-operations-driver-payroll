    /*
    |--------------------------------------------------------------------------
    | ADDITIONAL BUSINESS VALIDATION
    |--------------------------------------------------------------------------
    */

    public function withValidator(Validator $validator): void
    {
        $validator->after(function (Validator $validator) {

            /*
            |--------------------------------------------------------------------------
            | CORE FIELD CHECK
            |--------------------------------------------------------------------------
            */

            if (
                $validator->errors()->has('duty_assignment_id') ||
                $validator->errors()->has('driver_id')
            ) {
                return;
            }

            /*
            |--------------------------------------------------------------------------
            | SAME-DAY / CROSS-DAY DATETIME VALIDATION
            |--------------------------------------------------------------------------
            |
            | Valid:
            | 21 Sep 18:00 -> 21 Sep 23:00
            | 21 Sep 22:00 -> 22 Sep 02:00
            |
            | Invalid:
            | 21 Sep 18:00 -> 21 Sep 09:00
            |
            */

            $startDate = $this->input('start_date')
                ?: $this->input('duty_date');

            $endDate = $this->input('end_date')
                ?: $this->input('duty_date');

            $startTime = $this->input('start_time');
            $endTime = $this->input('end_time');

            if (
                !empty($startDate) &&
                !empty($endDate) &&
                !empty($startTime) &&
                !empty($endTime)
            ) {
                try {
                    $startDateTime = \Carbon\Carbon::createFromFormat(
                        'Y-m-d H:i',
                        "{$startDate} {$startTime}"
                    );

                    $endDateTime = \Carbon\Carbon::createFromFormat(
                        'Y-m-d H:i',
                        "{$endDate} {$endTime}"
                    );

                    if (
                        $endDateTime->lessThan($startDateTime)
                    ) {
                        $validator->errors()->add(
                            'end_time',
                            'End date and time cannot be before start date and time.'
                        );
                    }
                } catch (\Throwable $exception) {
                    // The standard date/time rules handle invalid formats.
                }
            }

            /*
            |--------------------------------------------------------------------------
            | VEHICLE TYPE COMPATIBILITY CHECK
            |--------------------------------------------------------------------------
            |
            | If both modern and legacy fields are supplied,
            | their resolved Vehicle Type IDs must match.
            |
            */

            $vehicleTypeId = $this->input('vehicle_type_id');

            $legacyVehicleType = trim(
                (string) $this->input('vehicle_type')
            );

            if (
                !empty($vehicleTypeId) &&
                $legacyVehicleType !== ''
            ) {
                $legacyResolvedId = null;

                if (ctype_digit($legacyVehicleType)) {
                    $legacyResolvedId = (int) $legacyVehicleType;
                } else {
                    $legacyResolvedId = \App\Models\VehicleType::query()
                        ->where('name', $legacyVehicleType)
                        ->value('id');

                    if (!$legacyResolvedId) {
                        $legacyResolvedId = \App\Models\VehicleType::query()
                            ->where('code', $legacyVehicleType)
                            ->value('id');
                    }
                }

                if (
                    $legacyResolvedId &&
                    (int) $vehicleTypeId !== (int) $legacyResolvedId
                ) {
                    $validator->errors()->add(
                        'vehicle_type_id',
                        'Selected vehicle type values do not match.'
                    );
                }
            }
        });
    }

