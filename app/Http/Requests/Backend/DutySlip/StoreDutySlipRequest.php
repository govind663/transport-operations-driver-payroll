    |--------------------------------------------------------------------------
    | PREPARE FOR VALIDATION
    |--------------------------------------------------------------------------
    |
    | Backward compatibility:
    | allowances[] -> driver_allowances[]
    | expenses[]   -> driver_expenses[]
    |
    | Create generates the final Duty Slip Number in the service.
    |
    */

    protected function prepareForValidation(): void
    {
        $data = [];

        /*
        |--------------------------------------------------------------------------
        | LEGACY ALLOWANCES
        |--------------------------------------------------------------------------
        */

        if (
            $this->has('allowances') &&
            !$this->has('driver_allowances')
        ) {
            $data['driver_allowances'] = $this->input('allowances');
        }

        /*
        |--------------------------------------------------------------------------
        | LEGACY EXPENSES
        |--------------------------------------------------------------------------
        */

        if (
            $this->has('expenses') &&
            !$this->has('driver_expenses')
        ) {
            $data['driver_expenses'] = $this->input('expenses');
        }

        /*
        |--------------------------------------------------------------------------
        | NORMALIZE EMPTY OPTIONAL IDs
        |--------------------------------------------------------------------------
        */

        foreach ([
            'slip_no',
            'driver_id',
            'vehicle_id',
            'vehicle_type_id',
        ] as $field) {
            if ($this->input($field) === '') {
                $data[$field] = null;
            }
        }

        /*
        |--------------------------------------------------------------------------
        | NORMALIZE LOCATIONS
        |--------------------------------------------------------------------------
        |
        | Trim leading/trailing spaces.
        | Store empty location input as null.
        |
        */

        foreach ([
            'pickup_location',
            'drop_location',
        ] as $field) {
            if ($this->exists($field)) {
                $value = $this->input($field);

                if (is_string($value)) {
                    $value = trim($value);
                    $data[$field] = $value !== '' ? $value : null;
                }
            }
        }

        /*
        |--------------------------------------------------------------------------
        | MERGE NORMALIZED VALUES
        |--------------------------------------------------------------------------
        */

        if (!empty($data)) {
            $this->merge($data);
        }
    }

