<?php

namespace App\Mail;

use App\Models\Driver;
use Illuminate\Mail\Mailable;
use Illuminate\Mail\Mailables\Attachment;
use Illuminate\Mail\Mailables\Content;
use Illuminate\Mail\Mailables\Envelope;
use Illuminate\Queue\SerializesModels;

class DriverWelcomeMail extends Mailable
{
    use SerializesModels;

    /*
    |--------------------------------------------------------------------------
    | DRIVER
    |--------------------------------------------------------------------------
    */

    public Driver $driver;


    /*
    |--------------------------------------------------------------------------
    | LOGIN EMAIL
    |--------------------------------------------------------------------------
    */

    public string $loginEmail;


    /*
    |--------------------------------------------------------------------------
    | TEMPORARY PASSWORD
    |--------------------------------------------------------------------------
    */

    public string $temporaryPassword;


    /*
    |--------------------------------------------------------------------------
    | LOGIN URL
    |--------------------------------------------------------------------------
    */

    public string $loginUrl;


    /*
    |--------------------------------------------------------------------------
    | USER ROLE
    |--------------------------------------------------------------------------
    */

    public string $role;


    /*
    |--------------------------------------------------------------------------
    | CREATE NEW MESSAGE INSTANCE
    |--------------------------------------------------------------------------
    */

    public function __construct(
        Driver $driver,
        string $loginEmail,
        string $temporaryPassword,
        ?string $role = null
    ) {

        /*
        |--------------------------------------------------------------------------
        | DRIVER
        |--------------------------------------------------------------------------
        */

        $this->driver = $driver;


        /*
        |--------------------------------------------------------------------------
        | LOGIN EMAIL
        |--------------------------------------------------------------------------
        */

        $this->loginEmail = $loginEmail;


        /*
        |--------------------------------------------------------------------------
        | TEMPORARY PASSWORD
        |--------------------------------------------------------------------------
        */

        $this->temporaryPassword =
            $temporaryPassword;


        /*
        |--------------------------------------------------------------------------
        | DYNAMIC USER ROLE
        |--------------------------------------------------------------------------
        |
        | Priority:
        |
        | 1. Role passed from UserService
        | 2. Role from linked User
        | 3. Driver
        |
        |--------------------------------------------------------------------------
        */

        $userRole =
            $role
            ?? $driver->user?->role
            ?? 'Driver';


        /*
        |--------------------------------------------------------------------------
        | FORMAT ROLE
        |--------------------------------------------------------------------------
        */

        $this->role =
            ucfirst(
                strtolower(
                    trim($userRole)
                )
            );


        /*
        |--------------------------------------------------------------------------
        | MASTERMIND TRAVELS LOGIN URL
        |--------------------------------------------------------------------------
        */

        $this->loginUrl =
            rtrim(
                config(
                    'app.url',
                    'https://transport.mastermindtravels.net'
                ),
                '/'
            ) . '/login';
    }


    /*
    |--------------------------------------------------------------------------
    | EMAIL ENVELOPE
    |--------------------------------------------------------------------------
    */

    public function envelope(): Envelope
    {
        return new Envelope(

            subject:
                'Welcome to Mastermind Travels | Your Driver Account is Ready',

        );
    }


    /*
    |--------------------------------------------------------------------------
    | EMAIL CONTENT
    |--------------------------------------------------------------------------
    */

    public function content(): Content
    {
        return new Content(

            view:
                'emails.driver-welcome',

            with: [

                /*
                |--------------------------------------------------------------------------
                | DRIVER
                |--------------------------------------------------------------------------
                */

                'driver' =>
                    $this->driver,


                /*
                |--------------------------------------------------------------------------
                | LOGIN EMAIL
                |--------------------------------------------------------------------------
                */

                'loginEmail' =>
                    $this->loginEmail,


                /*
                |--------------------------------------------------------------------------
                | TEMPORARY PASSWORD
                |--------------------------------------------------------------------------
                */

                'temporaryPassword' =>
                    $this->temporaryPassword,


                /*
                |--------------------------------------------------------------------------
                | LOGIN URL
                |--------------------------------------------------------------------------
                */

                'loginUrl' =>
                    $this->loginUrl,


                /*
                |--------------------------------------------------------------------------
                | ROLE
                |--------------------------------------------------------------------------
                */

                'role' =>
                    $this->role,

            ],

        );
    }


    /*
    |--------------------------------------------------------------------------
    | ATTACHMENTS
    |--------------------------------------------------------------------------
    */

    /**
     * Get the message attachments.
     *
     * @return array<int, Attachment>
     */
    public function attachments(): array
    {
        return [];
    }
}