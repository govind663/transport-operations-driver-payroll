<?php

namespace App\Services\User;

use App\Models\Driver;
use App\Models\User;
use Illuminate\Database\Eloquent\Collection;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Facades\Storage;

class UserService
{
    /*
    |--------------------------------------------------------------------------
    | GET ALL USERS
    |--------------------------------------------------------------------------
    */

    public function getUsers(): Collection
    {
        return User::latest()->get();
    }


    /*
    |--------------------------------------------------------------------------
    | FIND USER
    |--------------------------------------------------------------------------
    */

    public function findById(
        string|int $id
    ): User {

        return User::findOrFail($id);
    }


    /*
    |--------------------------------------------------------------------------
    | STORE USER
    |--------------------------------------------------------------------------
    */
    public function store(
        array $data
    ): User {

        return DB::transaction(function () use ($data) {

            /*
            |--------------------------------------------------------------------------
            | PROFILE IMAGE
            |--------------------------------------------------------------------------
            */

            if (
                isset($data['profile_image']) &&
                $data['profile_image']
            ) {

                $data['profile_image'] =
                    $data['profile_image']
                        ->store('users', 'public');
            }


            /*
            |--------------------------------------------------------------------------
            | PASSWORD
            |--------------------------------------------------------------------------
            */

            $data['password'] =
                Hash::make(
                    $data['password']
                );


            /*
            |--------------------------------------------------------------------------
            | CREATED BY
            |--------------------------------------------------------------------------
            */

            $data['created_by'] =
                Auth::id();


            /*
            |--------------------------------------------------------------------------
            | CREATE USER
            |--------------------------------------------------------------------------
            */
            return User::create($data);

        });
    }


    /*
    |--------------------------------------------------------------------------
    | CREATE DRIVER CREDENTIAL
    |--------------------------------------------------------------------------
    |
    | Creates login credentials for a Driver.
    |
    | Duplicate prevention:
    |
    | 1. If driver already has user_id -> return existing user.
    | 2. Check email.
    | 3. Check phone.
    | 4. If no user exists -> create new driver user.
    |
    |--------------------------------------------------------------------------
    */
    public function createDriverCredential(
        Driver $driver
    ): User {

        /*
        |--------------------------------------------------------------------------
        | EXISTING DRIVER USER
        |--------------------------------------------------------------------------
        */

        if (
            !empty($driver->user_id)
        ) {

            $user = User::findOrFail(
                $driver->user_id
            );

            /*
            |--------------------------------------------------------------------------
            | Sync Driver Photo
            |--------------------------------------------------------------------------
            */

            if (
                !empty($driver->driver_photo)
            ) {

                $user->update([
                    'profile_image' => $driver->driver_photo,
                ]);
            }

            return $user;
        }


        /*
        |--------------------------------------------------------------------------
        | FIND EXISTING USER
        |--------------------------------------------------------------------------
        */

        $user = null;


        /*
        |--------------------------------------------------------------------------
        | CHECK EMAIL
        |--------------------------------------------------------------------------
        */

        if (
            !empty($driver->email)
        ) {

            $user = User::query()
                ->where(
                    'email',
                    $driver->email
                )
                ->first();
        }


        /*
        |--------------------------------------------------------------------------
        | CHECK PHONE
        |--------------------------------------------------------------------------
        */

        if (
            !$user &&
            !empty($driver->mobile)
        ) {

            $user = User::query()
                ->where(
                    'phone',
                    $driver->mobile
                )
                ->first();
        }


        /*
        |--------------------------------------------------------------------------
        | DRIVER NAME
        |--------------------------------------------------------------------------
        */

        $name = trim(
            $driver->first_name .
            ' ' .
            ($driver->last_name ?? '')
        );


        /*
        |--------------------------------------------------------------------------
        | EXISTING USER FOUND
        |--------------------------------------------------------------------------
        */

        if ($user) {

            /*
            |--------------------------------------------------------------------------
            | Sync Driver Profile Image
            |--------------------------------------------------------------------------
            */

            if (
                !empty($driver->driver_photo)
            ) {

                $user->profile_image =
                    $driver->driver_photo;
            }

            $user->save();


            /*
            |--------------------------------------------------------------------------
            | Update Driver User ID
            |--------------------------------------------------------------------------
            */

            $driver->user_id =
                $user->id;

            $driver->save();


            return $user;
        }


        /*
        |--------------------------------------------------------------------------
        | CREATE DRIVER USER
        |--------------------------------------------------------------------------
        */

        $user = User::create([

            /*
            |--------------------------------------------------------------------------
            | Basic Information
            |--------------------------------------------------------------------------
            */

            'name' =>
                $name,

            'phone' =>
                $driver->mobile,

            'email' =>
                $driver->email,


            /*
            |--------------------------------------------------------------------------
            | PROFILE IMAGE
            |--------------------------------------------------------------------------
            |
            | Use driver's uploaded photo as user's profile image.
            |
            |--------------------------------------------------------------------------
            */

            'profile_image' =>
                $driver->driver_photo,


            /*
            |--------------------------------------------------------------------------
            | DEFAULT PASSWORD
            |--------------------------------------------------------------------------
            */

            'password' =>
                Hash::make(
                    'Driver@123'
                ),


            /*
            |--------------------------------------------------------------------------
            | DRIVER ROLE
            |--------------------------------------------------------------------------
            */

            'role' =>
                User::ROLE_DRIVER,


            /*
            |--------------------------------------------------------------------------
            | ACTIVE
            |--------------------------------------------------------------------------
            */

            'status' =>
                User::STATUS_ACTIVE,


            /*
            |--------------------------------------------------------------------------
            | CREATED BY
            |--------------------------------------------------------------------------
            */

            'created_by' =>
                Auth::id(),

        ]);


        /*
        |--------------------------------------------------------------------------
        | UPDATE DRIVER USER ID
        |--------------------------------------------------------------------------
        */

        $driver->user_id =
            $user->id;

        $driver->save();


        /*
        |--------------------------------------------------------------------------
        | RETURN USER
        |--------------------------------------------------------------------------
        */

        return $user;
    }


    /*
    |--------------------------------------------------------------------------
    | UPDATE USER
    |--------------------------------------------------------------------------
    */
    public function update(
        User $user,
        array $data
    ): User {

        return DB::transaction(
            function () use ($user, $data) {

                /*
                |--------------------------------------------------------------------------
                | PROFILE IMAGE
                |--------------------------------------------------------------------------
                */
                if (
                    isset($data['profile_image']) &&
                    $data['profile_image']
                ) {

                    /*
                    |--------------------------------------------------------------------------
                    | DELETE OLD IMAGE
                    |--------------------------------------------------------------------------
                    */
                    if (
                        $user->profile_image &&
                        Storage::disk('public')
                            ->exists(
                                $user->profile_image
                            )
                    ) {

                        Storage::disk('public')
                            ->delete(
                                $user->profile_image
                            );
                    }


                    /*
                    |--------------------------------------------------------------------------
                    | STORE NEW IMAGE
                    |--------------------------------------------------------------------------
                    */
                    $data['profile_image'] =
                        $data['profile_image']
                            ->store(
                                'users',
                                'public'
                            );
                }


                /*
                |--------------------------------------------------------------------------
                | UPDATED BY
                |--------------------------------------------------------------------------
                */
                $data['updated_by'] =
                    Auth::id();


                /*
                |--------------------------------------------------------------------------
                | UPDATE USER
                |--------------------------------------------------------------------------
                */
                $user->update($data);


                /*
                |--------------------------------------------------------------------------
                | RETURN FRESH USER
                |--------------------------------------------------------------------------
                */
                return $user->refresh();

            }
        );
    }


    /*
    |--------------------------------------------------------------------------
    | DELETE USER
    |--------------------------------------------------------------------------
    */
    public function delete(
        User $user
    ): bool {

        $user->update([
            'deleted_by' => Auth::id(),
        ]);

        return $user->delete();
    }
}