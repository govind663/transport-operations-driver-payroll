<?php

namespace App\Services\User;

use App\Models\UserHistory;
use Illuminate\Support\Facades\Auth;

class UserActivityService
{
    /*
    |--------------------------------------------------------------------------
    | LOG ACTIVITY
    |--------------------------------------------------------------------------
    */

    public function log(
        string $activity,
        ?int $userId = null
    ): ?UserHistory {

        try {

            $request = request();

            /*
            |--------------------------------------------------------------------------
            | USER ID
            |--------------------------------------------------------------------------
            |
            | By default activity kis logged-in user ne perform ki
            |
            |--------------------------------------------------------------------------
            */

            $userId = $userId ?? Auth::id();


            /*
            |--------------------------------------------------------------------------
            | IP ADDRESS
            |--------------------------------------------------------------------------
            */

            $ipAddress = $request->ip();


            /*
            |--------------------------------------------------------------------------
            | USER AGENT
            |--------------------------------------------------------------------------
            */

            $userAgent = $request->userAgent();


            /*
            |--------------------------------------------------------------------------
            | DEVICE
            |--------------------------------------------------------------------------
            */

            $device = $this->detectDevice(
                $userAgent
            );


            /*
            |--------------------------------------------------------------------------
            | CREATE HISTORY
            |--------------------------------------------------------------------------
            */

            return UserHistory::create([

                'user_id' =>
                    $userId,

                'activity' =>
                    $activity,

                'ip_address' =>
                    $ipAddress,

                'city' =>
                    null,

                'country' =>
                    null,

                'device' =>
                    $device,

                'user_agent' =>
                    $userAgent,

                'activity_time' =>
                    now(),

            ]);

        } catch (\Throwable $e) {

            /*
            |--------------------------------------------------------------------------
            | IMPORTANT
            |--------------------------------------------------------------------------
            |
            | Activity logging failure should NEVER break
            | the main User CRUD operation.
            |
            |--------------------------------------------------------------------------
            */

            report($e);

            return null;
        }
    }


    /*
    |--------------------------------------------------------------------------
    | DEVICE DETECTION
    |--------------------------------------------------------------------------
    */

    protected function detectDevice(
        ?string $userAgent
    ): string {

        if (empty($userAgent)) {
            return 'Unknown';
        }

        $userAgent = strtolower(
            $userAgent
        );


        /*
        |--------------------------------------------------------------------------
        | TABLET
        |--------------------------------------------------------------------------
        */

        if (
            str_contains(
                $userAgent,
                'ipad'
            ) ||
            str_contains(
                $userAgent,
                'tablet'
            )
        ) {
            return 'Tablet';
        }


        /*
        |--------------------------------------------------------------------------
        | MOBILE
        |--------------------------------------------------------------------------
        */

        if (
            str_contains(
                $userAgent,
                'mobile'
            ) ||
            str_contains(
                $userAgent,
                'android'
            )
        ) {
            return 'Mobile';
        }


        /*
        |--------------------------------------------------------------------------
        | DESKTOP
        |--------------------------------------------------------------------------
        */

        return 'Desktop';
    }
}