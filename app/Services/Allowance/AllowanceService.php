<?php

namespace App\Services\Allowance;

use App\Models\Allowance;
use Illuminate\Contracts\Pagination\LengthAwarePaginator;
use Illuminate\Support\Facades\Auth;
use Illuminate\Support\Facades\DB;

class AllowanceService
{
    /*
    |--------------------------------------------------------------------------
    | GET ALLOWANCES
    |--------------------------------------------------------------------------
    */

    public function getAllowances(
        int $perPage = 10000000000000
    ): LengthAwarePaginator {

        return Allowance::query()
            ->with([
                'createdBy',
                'updatedBy',
            ])
            ->latest('id')
            ->paginate($perPage);
    }


    /*
    |--------------------------------------------------------------------------
    | FIND ALLOWANCE
    |--------------------------------------------------------------------------
    */

    public function findById(
        string|int $id
    ): Allowance {

        return Allowance::query()
            ->with([
                'createdBy',
                'updatedBy',
            ])
            ->findOrFail($id);
    }


    /*
    |--------------------------------------------------------------------------
    | STORE
    |--------------------------------------------------------------------------
    */

    public function store(
        array $data
    ): Allowance {

        return DB::transaction(function () use ($data) {

            /*
            |--------------------------------------------------------------------------
            | Created By
            |--------------------------------------------------------------------------
            */

            $data['created_by'] = Auth::id();


            /*
            |--------------------------------------------------------------------------
            | Updated By
            |--------------------------------------------------------------------------
            */

            $data['updated_by'] = Auth::id();


            /*
            |--------------------------------------------------------------------------
            | Calculation Type
            |--------------------------------------------------------------------------
            */

            $data['calculation_type'] =
                $data['calculation_type']
                ?? Allowance::CALCULATION_FIXED;


            /*
            |--------------------------------------------------------------------------
            | Amount
            |--------------------------------------------------------------------------
            */

            $data['amount'] =
                $data['amount']
                ?? 0;


            /*
            |--------------------------------------------------------------------------
            | Status
            |--------------------------------------------------------------------------
            */

            $data['status'] =
                $data['status']
                ?? Allowance::STATUS_ACTIVE;


            /*
            |--------------------------------------------------------------------------
            | Create Allowance
            |--------------------------------------------------------------------------
            */

            return Allowance::create($data);
        });
    }


    /*
    |--------------------------------------------------------------------------
    | UPDATE
    |--------------------------------------------------------------------------
    */

    public function update(
        Allowance $allowance,
        array $data
    ): Allowance {

        return DB::transaction(function () use (
            $allowance,
            $data
        ) {

            /*
            |--------------------------------------------------------------------------
            | Updated By
            |--------------------------------------------------------------------------
            */

            $data['updated_by'] = Auth::id();


            /*
            |--------------------------------------------------------------------------
            | Calculation Type
            |--------------------------------------------------------------------------
            */

            $data['calculation_type'] =
                $data['calculation_type']
                ?? $allowance->calculation_type;


            /*
            |--------------------------------------------------------------------------
            | Amount
            |--------------------------------------------------------------------------
            */

            $data['amount'] =
                $data['amount']
                ?? $allowance->amount;


            /*
            |--------------------------------------------------------------------------
            | Update Allowance
            |--------------------------------------------------------------------------
            */

            $allowance->update($data);


            /*
            |--------------------------------------------------------------------------
            | Return Fresh Model
            |--------------------------------------------------------------------------
            */

            return $allowance->fresh([
                'createdBy',
                'updatedBy',
            ]);
        });
    }


    /*
    |--------------------------------------------------------------------------
    | DELETE
    |--------------------------------------------------------------------------
    */

    public function delete(
        Allowance $allowance
    ): bool {

        return DB::transaction(function () use (
            $allowance
        ) {

            /*
            |--------------------------------------------------------------------------
            | Deleted By
            |--------------------------------------------------------------------------
            */

            $allowance->deleted_by = Auth::id();

            $allowance->save();


            /*
            |--------------------------------------------------------------------------
            | Soft Delete
            |--------------------------------------------------------------------------
            */

            return $allowance->delete();
        });
    }
}
